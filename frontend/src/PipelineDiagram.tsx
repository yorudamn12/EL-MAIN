// Live pipeline architecture diagram: one box per stage, highlighted while it runs, greyed once done.
// Self-contained (this file + PipelineDiagram.css); remove the one <PipelineDiagram/> line in App.tsx to drop it.
import { useState } from "react";
import "./PipelineDiagram.css";
import type { Pipeline, Step } from "./api";

type StageState = "pending" | "running" | "partial" | "done" | "reused" | "failed" | "cancelled";

interface StageDef { id: string; title: string; text: string }

// Order and labels follow the backend's stages (GET /meta → stages); the one-line texts describe the project's design.
const FLOW: StageDef[] = [
  { id: "preflight", title: "Check setup", text: "GPU, disk, model access, datasets" },
  { id: "baseline", title: "Benchmark base model", text: "Score the untrained model" },
  { id: "diagnose", title: "Find weaknesses", text: "Probe problems → ranked weaknesses" },
  { id: "choose_target", title: "Choose the target", text: "Pick the weakness to aim at" },
  { id: "build_data", title: "Build training data", text: "Problems generated by code, per arm" },
];
const LOOP: StageDef[] = [
  { id: "train", title: "Train", text: "QLoRA fine-tune of one arm" },
  { id: "evaluate", title: "Evaluate", text: "Re-test the trained model" },
];
const END: StageDef = { id: "compare", title: "Compare results", text: "Targeted vs matched control, with CIs" };

const STATE_LABEL: Record<StageState, string> = {
  pending: "WAITING", running: "RUNNING", partial: "IN PROGRESS", done: "DONE", reused: "REUSED",
  failed: "FAILED", cancelled: "CANCELLED",
};

function summarize(steps: Step[]): { state: StageState; done: number; total: number; current?: Step } {
  const total = steps.length;
  if (!total) return { state: "pending", done: 0, total: 0 };
  const done = steps.filter((s) => s.status === "done" || s.status === "skipped").length;
  const current = steps.find((s) => s.status === "running");
  if (current) return { state: "running", done, total, current };
  if (steps.some((s) => s.status === "failed")) return { state: "failed", done, total };
  if (steps.some((s) => s.status === "cancelled")) return { state: "cancelled", done, total };
  if (done === total) return { state: steps.every((s) => s.status === "skipped") ? "reused" : "done", done, total };
  return { state: done > 0 ? "partial" : "pending", done, total };
}

function Node({ def, steps }: { def: StageDef; steps: Step[] }) {
  const { state, done, total, current } = summarize(steps);
  const frac = current ? current.progress.fraction : 0;
  return (
    <div className={`pd-node ${state}`} aria-current={state === "running" ? "step" : undefined}>
      <div className="pd-top">
        <span className="pd-title">{def.title}</span>
        <span className="pd-badge">{state === "done" ? "✓ " : ""}{STATE_LABEL[state]}</span>
      </div>
      <p>{def.text}</p>
      {total > 1 && <div className="pd-count">{done}/{total} steps</div>}
      {current && (
        <div className="pd-live">
          <span>{current.label}</span>
          <div className="pd-bar"><i style={{ width: `${Math.round(frac * 100)}%` }} /></div>
        </div>
      )}
    </div>
  );
}

const Arrow = () => <span className="pd-arrow" aria-hidden="true">→</span>;

function readOpen(): boolean {
  try { return localStorage.getItem("dm.pipelineDiagram") !== "off"; } catch { return true; }
}

export default function PipelineDiagram({ pipeline }: { pipeline: Pipeline | null }) {
  const [open, setOpen] = useState(readOpen);
  const toggle = () => {
    setOpen((v) => {
      try { localStorage.setItem("dm.pipelineDiagram", v ? "off" : "on"); } catch { /* storage unavailable */ }
      return !v;
    });
  };
  const by = (stage: string) => (pipeline?.steps ?? []).filter((s) => s.stage === stage);
  return (
    <section className="panel pd-panel">
      <div className="panel-heading">
        <div>
          <div className="eyebrow">PIPELINE ARCHITECTURE</div>
          <h3>{pipeline ? pipeline.name : "No experiment selected"}</h3>
        </div>
        <button className="text-button" onClick={toggle}>{open ? "Hide diagram" : "Show diagram"}</button>
      </div>
      {open && (
        <>
          <div className="pd-legend">
            <span><i className="running" /> Running now</span>
            <span><i className="partial" /> Between steps</span>
            <span><i className="done" /> Done</span>
            <span><i className="pending" /> Waiting</span>
            <span><i className="failed" /> Failed / cancelled</span>
          </div>
          <div className="pd-flow">
            {FLOW.map((d) => (
              <div className="pd-cell" key={d.id}><Node def={d} steps={by(d.id)} /><Arrow /></div>
            ))}
            <div className="pd-loop">
              <div className="pd-loop-label">↻ for each arm × seed</div>
              <div className="pd-loop-row">
                <Node def={LOOP[0]} steps={by("train")} />
                <Arrow />
                <Node def={LOOP[1]} steps={by("evaluate")} />
              </div>
            </div>
            <div className="pd-cell"><Arrow /><Node def={END} steps={by("compare")} /></div>
          </div>
          {!pipeline && <p className="panel-description">Select or launch an experiment to see its stages light up.</p>}
        </>
      )}
    </section>
  );
}
